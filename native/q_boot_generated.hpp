inline void q_boot_normal(State& mem,uint32_t calibration_word=5200) {
    std::fill(mem.ram.begin(),mem.ram.end(),uint8_t(0));
    std::fill(mem.sdram.begin(),mem.sdram.end(),uint8_t(0));
    for(const auto& word:boot_q)mem.wu(0x20000000u+word.offset,word.value);
    const float x=f32(static_cast<float>(calibration_word));
    mem.wf(0x20000284u,x>=3000.f && x<from_bits(0x45dac001u)?x:5200.f);
}
